// One-off data-verification script: fetches the canonical surah ayah-counts and
// juz' (para) starting points from the Al Quran Cloud API (api.alquran.cloud,
// keyless, built on the Uthmani/King Fahd Complex standard text) and
// cross-checks them against this repo's hand-typed tables:
//   - data/quranSurahs.ts  (QURAN_SURAHS ayah counts)
//   - lib/quranPlan.ts     (JUZ_START juz'-boundary table)
//
// Run via the "Verify Juz Boundaries" GitHub Action (has real internet
// access; this repo's dev sandbox does not), not as part of the normal build.
//
// Usage: node scripts/fetch-juz-boundaries.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));

function extractLocalQuranSurahs() {
  const src = readFileSync(`${repoRoot}/data/quranSurahs.ts`, "utf8");
  const rows = [...src.matchAll(/\{ number: (\d+), nameAr: "[^"]*", nameEn: "[^"]*", ayahCount: (\d+) \}/g)];
  return new Map(rows.map((m) => [Number(m[1]), Number(m[2])]));
}

function extractLocalJuzStart() {
  const src = readFileSync(`${repoRoot}/lib/quranPlan.ts`, "utf8");
  const rows = [...src.matchAll(/\{ surah: (\d+), ayah: (\d+) \},? \/\/ (\d+)/g)];
  return rows.map((m) => ({ surah: Number(m[1]), ayah: Number(m[2]), juz: Number(m[3]) }));
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function fetchJson(url, attempt = 1) {
  const res = await fetch(url);
  if (res.status === 429 && attempt <= 5) {
    const backoffMs = attempt * 1500;
    console.log(`  rate limited, retrying in ${backoffMs}ms (attempt ${attempt})...`);
    await sleep(backoffMs);
    return fetchJson(url, attempt + 1);
  }
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

console.log("Fetching surah list (ayah counts) from Al Quran Cloud...");
const surahMeta = await fetchJson("https://api.alquran.cloud/v1/surah");
const remoteSurahAyahCounts = new Map(
  surahMeta.data.map((s) => [s.number, s.numberOfAyahs])
);

console.log("Fetching juz' boundaries (1..30) from Al Quran Cloud...");
const remoteJuzStart = [];
for (let juz = 1; juz <= 30; juz++) {
  if (juz > 1) await sleep(500);
  const data = await fetchJson(`https://api.alquran.cloud/v1/juz/${juz}/quran-uthmani`);
  const firstAyah = data.data.ayahs[0];
  const start = { surah: firstAyah.surah.number, ayah: firstAyah.numberInSurah };
  remoteJuzStart.push(start);
  console.log(`Juz ${juz}: surah ${start.surah}, ayah ${start.ayah}`);
}

let ok = true;

// 1) Cross-check surah ayah counts against the local table.
console.log("\n--- Checking data/quranSurahs.ts ayah counts ---");
const localSurahAyahCounts = extractLocalQuranSurahs();
for (const [number, remoteCount] of remoteSurahAyahCounts) {
  const localCount = localSurahAyahCounts.get(number);
  if (localCount !== remoteCount) {
    console.error(`FAIL: surah ${number} ayahCount mismatch — local=${localCount} remote=${remoteCount}`);
    ok = false;
  }
}
if (ok) console.log("All 114 surah ayah counts match.");

// 2) Cross-check the JUZ_START table against the local table.
console.log("\n--- Checking lib/quranPlan.ts JUZ_START ---");
const localJuzStart = extractLocalJuzStart();
let juzOk = true;
for (let i = 0; i < 30; i++) {
  const local = localJuzStart[i];
  const remote = remoteJuzStart[i];
  if (!local || local.surah !== remote.surah || local.ayah !== remote.ayah) {
    console.error(
      `MISMATCH: juz ${i + 1} — local=${local ? `${local.surah}:${local.ayah}` : "MISSING"} remote=${remote.surah}:${remote.ayah}`
    );
    juzOk = false;
  }
}
if (juzOk) {
  console.log("All 30 juz' boundaries match the local table exactly. No fix needed.");
} else {
  console.log("Differences found — writing corrected table to scripts/juz-boundaries-verified.ts");
  ok = false;
}

const tsLines = remoteJuzStart
  .map((r, i) => `  { surah: ${r.surah}, ayah: ${r.ayah} }, // ${i + 1}`)
  .join("\n");
writeFileSync(
  `${repoRoot}/scripts/juz-boundaries-verified.ts`,
  `// Generated by scripts/fetch-juz-boundaries.mjs from api.alquran.cloud. Source of truth for JUZ_START in lib/quranPlan.ts.\nconst JUZ_START: { surah: number; ayah: number }[] = [\n${tsLines}\n];\n`
);

console.log(ok ? "\nRESULT: verified, no changes needed." : "\nRESULT: mismatches found — see juz-boundaries-verified.ts");
if (!ok) process.exit(1);
